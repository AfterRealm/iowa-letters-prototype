#!/usr/bin/env node
// Generate assets/js/author-config.js at deploy time.
//
// As of v0.3.0 the Omeka credentials live SERVER-SIDE only — they are read
// by netlify/functions/post-letter.js from Netlify environment variables
// and never reach the browser. This script writes only the non-secret
// configuration the browser needs: API_BASE, Resource Template / Item Set
// ids, and the Dublin Core property id table. The function endpoint path
// is hardcoded in add-letter.js.
//
// Optional Netlify env vars:
//   OMEKA_API_BASE                default: https://iowa.dev.01.ngrok.dev/api
//   OMEKA_RESOURCE_TEMPLATE_ID    default: 2
//   OMEKA_ITEM_SET_ID             default: 1
const fs = require('node:fs');
const path = require('node:path');

const OUT = path.join(__dirname, '..', 'assets', 'js', 'author-key.js');

const API_BASE = process.env.OMEKA_API_BASE || 'https://iowa.dev.01.ngrok.dev/api';
const RT_ID = Number(process.env.OMEKA_RESOURCE_TEMPLATE_ID || 2);
const IS_ID = Number(process.env.OMEKA_ITEM_SET_ID || 1);

const body = `// Generated by scripts/build-author-key.js at deploy time. Do not edit.
// As of v0.3.0 this file contains NO credentials — the Omeka API key lives
// in Netlify env vars and is read server-side by /.netlify/functions/post-letter.
window.OMEKA_AUTHOR_KEY = {
  API_BASE: ${JSON.stringify(API_BASE)},
  RESOURCE_TEMPLATE_ID: ${RT_ID},
  ITEM_SET_ID: ${IS_ID},
  PROPS: {
    title: 1, creator: 2, subject: 3, description: 4,
    date: 7, type: 8, format: 9, source: 11, language: 12,
    rights: 15, spatial: 40, temporal: 41,
  },
};
`;

fs.writeFileSync(OUT, body, 'utf8');
console.log(`[build-author-key] wrote ${OUT}`);
console.log(`[build-author-key]   API_BASE=${API_BASE}  RT=${RT_ID}  IS=${IS_ID}`);
console.log(`[build-author-key]   (no credentials in client config — see /.netlify/functions/post-letter)`);
