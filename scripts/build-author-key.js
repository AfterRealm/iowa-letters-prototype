#!/usr/bin/env node
// Generate assets/js/author-key.js from environment variables at deploy time.
//
// Required Netlify env vars (Site settings → Environment variables):
//     OMEKA_AUTHOR_KEY_ID       32-char base62 string
//     OMEKA_AUTHOR_KEY_CRED     32-char base62 string
//
// Optional, with sensible defaults:
//     OMEKA_API_BASE            default: https://iowa.dev.01.ngrok.dev/api
//     OMEKA_RESOURCE_TEMPLATE_ID  default: 2
//     OMEKA_ITEM_SET_ID         default: 1
//
// If the required env vars are missing, this script writes a stub file that
// surfaces a clear "credentials not configured" message in the browser
// rather than silently failing.
const fs = require('node:fs');
const path = require('node:path');

const OUT = path.join(__dirname, '..', 'assets', 'js', 'author-key.js');

const KEY_ID = process.env.OMEKA_AUTHOR_KEY_ID || '';
const KEY_CRED = process.env.OMEKA_AUTHOR_KEY_CRED || '';
const API_BASE = process.env.OMEKA_API_BASE || 'https://iowa.dev.01.ngrok.dev/api';
const RT_ID = Number(process.env.OMEKA_RESOURCE_TEMPLATE_ID || 2);
const IS_ID = Number(process.env.OMEKA_ITEM_SET_ID || 1);

const haveKey = Boolean(KEY_ID && KEY_CRED);

const body = `// Generated by scripts/build-author-key.js at deploy time. Do not edit.
// Source: Netlify build environment variables.
window.OMEKA_AUTHOR_KEY = {
  KEY_ID:   ${JSON.stringify(KEY_ID)},
  KEY_CRED: ${JSON.stringify(KEY_CRED)},
  API_BASE: ${JSON.stringify(API_BASE)},
  RESOURCE_TEMPLATE_ID: ${RT_ID},
  ITEM_SET_ID: ${IS_ID},
  PROPS: {
    title: 1, creator: 2, subject: 3, description: 4,
    date: 7, type: 8, format: 9, source: 11, language: 12,
    rights: 15, spatial: 40, temporal: 41,
  },
};
`;

fs.writeFileSync(OUT, body, 'utf8');

if (haveKey) {
  console.log(`[build-author-key] wrote ${OUT}`);
  console.log(`[build-author-key]   API_BASE=${API_BASE}`);
  console.log(`[build-author-key]   RESOURCE_TEMPLATE_ID=${RT_ID}  ITEM_SET_ID=${IS_ID}`);
} else {
  console.log(`[build-author-key] WARNING: OMEKA_AUTHOR_KEY_ID / OMEKA_AUTHOR_KEY_CRED not set.`);
  console.log(`[build-author-key] Wrote stub — authoring form will surface "credentials not configured".`);
}
